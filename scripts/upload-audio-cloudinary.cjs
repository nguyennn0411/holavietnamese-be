#!/usr/bin/env node
// Run with Node 20+: node --env-file=.env.cloudinary scripts/upload-audio-cloudinary.cjs
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');

const backend = path.resolve(__dirname, '..');
const frontend = path.resolve(backend, '..', 'FE', 'holavietnamese_fe');
const backendMedia = path.join(backend, 'src/main/resources/static/media');
const alphabetMedia = path.join(frontend, 'public/media/alphabet');
const clientMapFile = path.join(frontend, 'src/components/common/cloudinaryAudioUrls.js');
const stateFile = path.join(backend, '.verification/cloudinary-audio-upload-state.json');
const dryRun = process.argv.includes('--dry-run');
const cloud = process.env.CLOUDINARY_CLOUD_NAME;
const key = process.env.CLOUDINARY_API_KEY;
const secret = process.env.CLOUDINARY_API_SECRET;
const folder = (process.env.CLOUDINARY_AUDIO_FOLDER || 'hola-vietnamese/audio').replace(/^\/+|\/+$/g, '');

if (!/^[A-Za-z0-9_-]+(?:\/[A-Za-z0-9_-]+)*$/.test(folder)) throw Error('Invalid CLOUDINARY_AUDIO_FOLDER');
if (!dryRun && (!cloud || !key || !secret)) {
  throw Error('Set CLOUDINARY_CLOUD_NAME, CLOUDINARY_API_KEY and CLOUDINARY_API_SECRET before upload.');
}
if (cloud && !/^[A-Za-z0-9_-]+$/.test(cloud)) throw Error('Invalid CLOUDINARY_CLOUD_NAME');

function wavFiles(dir, urlPrefix) {
  if (!fs.existsSync(dir)) throw Error(`Missing audio directory: ${dir}`);
  return fs.readdirSync(dir, { withFileTypes: true })
    .filter(entry => entry.isFile() && entry.name.toLowerCase().endsWith('.wav'))
    .map(entry => ({ path: path.join(dir, entry.name), url: `${urlPrefix}/${entry.name}` }));
}

const files = [
  ...wavFiles(path.join(backendMedia, 'foundation'), '/media/foundation'),
  ...wavFiles(path.join(backendMedia, 'pronunciation'), '/media/pronunciation'),
  ...wavFiles(alphabetMedia, '/media/alphabet'),
].sort((a, b) => a.url.localeCompare(b.url, 'en'));

for (const file of files) {
  const bytes = fs.readFileSync(file.path);
  if (bytes.length < 1000 || bytes.toString('ascii', 0, 4) !== 'RIFF' || bytes.toString('ascii', 8, 12) !== 'WAVE') {
    throw Error(`Invalid WAV: ${file.path}`);
  }
  file.sha256 = crypto.createHash('sha256').update(bytes).digest('hex');
  file.bytes = bytes;
  file.publicId = `${folder}/${file.url.slice('/media/'.length, -'.wav'.length)}`;
}
if (new Set(files.map(file => file.url)).size !== files.length) throw Error('Duplicate audio paths');
console.log(`Checked ${files.length} WAV files (${(files.reduce((sum, file) => sum + file.bytes.length, 0) / 1048576).toFixed(1)} MiB).`);
if (dryRun) process.exit(0);

const state = fs.existsSync(stateFile) ? JSON.parse(fs.readFileSync(stateFile, 'utf8')) : {};
const urls = {};
const expectedPrefix = `https://res.cloudinary.com/${cloud}/video/upload/`;
for (const file of files) {
  const previous = state[file.url];
  if (previous?.sha256 === file.sha256 && previous.publicId === file.publicId && previous.url?.startsWith(expectedPrefix)) {
    urls[file.url] = previous.url;
  }
}
let uploaded = 0;
let reused = 0;

function save() {
  fs.mkdirSync(path.dirname(stateFile), { recursive: true });
  fs.writeFileSync(stateFile, JSON.stringify(state, null, 2) + '\n');
  fs.writeFileSync(clientMapFile, `// Generated by BE/scripts/upload-audio-cloudinary.cjs.\nexport default ${JSON.stringify(urls, null, 2)};\n`);
}

async function upload(file) {
  const previous = state[file.url];
  if (previous?.sha256 === file.sha256 && previous.publicId === file.publicId && previous.url?.startsWith(expectedPrefix)) {
    reused++;
    return previous.url;
  }
  const params = {
    invalidate: 'true',
    overwrite: 'true',
    public_id: file.publicId,
    timestamp: String(Math.floor(Date.now() / 1000)),
  };
  const payload = Object.entries(params).sort(([a], [b]) => a.localeCompare(b, 'en'))
    .map(([name, value]) => `${name}=${value}`).join('&');
  const signature = crypto.createHash('sha1').update(payload + secret).digest('hex');
  const form = new FormData();
  for (const [name, value] of Object.entries(params)) form.set(name, value);
  form.set('api_key', key);
  form.set('signature', signature);
  form.set('file', new Blob([file.bytes], { type: 'audio/wav' }), path.basename(file.path));
  const response = await fetch(`https://api.cloudinary.com/v1_1/${cloud}/video/upload`, {
    method: 'POST', body: form, signal: AbortSignal.timeout(60_000),
  });
  const result = await response.json();
  if (!response.ok) throw Error(`Cloudinary rejected ${file.url}: ${response.status} ${result.error?.message || 'upload failed'}`);
  if (result.resource_type !== 'video' || result.public_id !== file.publicId || result.format !== 'wav' ||
      typeof result.secure_url !== 'string' || !result.secure_url.startsWith(expectedPrefix)) {
    throw Error(`Unexpected Cloudinary response for ${file.url}`);
  }
  uploaded++;
  state[file.url] = { sha256: file.sha256, publicId: file.publicId, url: result.secure_url };
  return result.secure_url;
}

async function main() {
  let cursor = 0;
  let completed = 0;
  let failure;
  async function worker() {
    while (cursor < files.length && !failure) {
      const file = files[cursor++];
      try {
        urls[file.url] = await upload(file);
        completed++;
        if (completed % 20 === 0 || completed === files.length) {
          save();
          console.log(`${completed}/${files.length}: ${uploaded} uploaded, ${reused} unchanged`);
        }
      } catch (error) {
        failure = error;
      }
    }
  }
  await Promise.all(Array.from({ length: 4 }, worker));
  save();
  if (failure) throw failure;
  console.log(`Done. ${Object.keys(urls).length} Cloudinary URLs written to ${clientMapFile}.`);
}

main().catch(error => {
  save();
  console.error(error.message);
  process.exitCode = 1;
});
